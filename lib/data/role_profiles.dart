/// 岗位行动建议。
class RoleAction {
  final String action;

  /// cert | experience | skill | education | portfolio | other。
  final String category;

  /// 预估录取概率提升（0–100）。
  final int expectedGain;

  /// low | medium | high。
  final String effort;
  final String timeEstimate;
  final String rationale;
  final List<String> resources;

  const RoleAction({
    required this.action,
    this.category = 'other',
    this.expectedGain = 0,
    this.effort = 'medium',
    this.timeEstimate = '',
    this.rationale = '',
    this.resources = const [],
  });
}

/// 一个岗位/方向的画像。
class RoleProfile {
  final String id;
  final String name;
  final List<String> aliases;

  /// 细分行业（如 互联网/金融-证券/量化/医疗/制造/教育K12）。
  final String? industry;

  /// 职级：校招|初级|中级|高级|资深|专家|管理。
  final String? level;

  /// 同族岗位 id（便于横向对照/跳转）。
  final List<String> relatedRoles;

  /// 必备/加分证书（mandatory=true 为硬性要求）。
  final List<({String name, bool mandatory})> requiredCerts;
  final List<String> coreSkills;
  final List<String> typicalExperiences;
  final List<String> bonusItems;
  final List<RoleAction> actions;

  const RoleProfile({
    required this.id,
    required this.name,
    required this.aliases,
    this.industry,
    this.level,
    this.relatedRoles = const [],
    this.requiredCerts = const [],
    this.coreSkills = const [],
    this.typicalExperiences = const [],
    this.bonusItems = const [],
    this.actions = const [],
  });
}

/// 画像库入口。
class RoleProfiles {
  RoleProfiles._();

  static List<RoleProfile> get all => _all;

  /// 按 targetRole 文本打分匹配画像；中英混合、行业+职级+岗位；
  /// 取最高分画像，无匹配返回 null。
  static RoleProfile? match(String? roleText) {
    final raw = (roleText ?? '').trim().toLowerCase();
    if (raw.isEmpty) return null;

    RoleProfile? best;
    var bestScore = 0;
    for (final p in _all) {
      var score = 0;
      for (final a in p.aliases) {
        final alias = a.toLowerCase().trim();
        if (alias.isEmpty) continue;
        if (_hasCjk(alias)) {
          // 中文别名：出现即加分；别名越长越具体，权重越高。
          if (raw.contains(alias)) score += 10 + alias.runes.length * 3;
        } else if (_isShortAscii(alias)) {
          // 短 ASCII（go/ai/nlp 等）必须整词匹配，避免子串误伤。
          if (_containsToken(raw, alias)) score += 8;
        } else if (raw.contains(alias)) {
          score += 6 + alias.length;
        }
      }
      final level = p.level;
      if (level != null && _levelHit(raw, level)) score += 6;
      final industry = p.industry;
      if (industry != null && _industryHit(raw, industry)) score += 4;
      if (score > bestScore) {
        bestScore = score;
        best = p;
      }
    }
    return bestScore > 0 ? best : null;
  }

  static bool _hasCjk(String s) => s.runes.any((c) => c > 0x2e7f);

  static bool _isShortAscii(String s) =>
      s.length <= 3 && s.codeUnits.every((c) => c < 128);

  static bool _containsToken(String hay, String token) =>
      hay.split(RegExp(r'[^a-z0-9+#]+')).contains(token);

  static bool _levelHit(String raw, String level) {
    final keys = _levelKeys[level];
    if (keys == null) return raw.contains(level.toLowerCase());
    return keys.any(raw.contains);
  }

  static bool _industryHit(String raw, String industry) => industry
      .toLowerCase()
      .split(RegExp(r'[/、,，|]'))
      .map((e) => e.trim())
      .where((e) => e.isNotEmpty)
      .any(raw.contains);
}

