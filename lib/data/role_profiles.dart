/// 关键词打分匹配目标岗位，取最高分画像，无匹配返回 null。
///
/// 画像维度：细分行业（industry）与职级（level），同一岗位族下可有
/// 校招/初级 与 高级/资深/专家 等多条画像，体现证据层级差异。
